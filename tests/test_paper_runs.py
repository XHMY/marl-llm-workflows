def test_header_and_project() -> None:
    text = PAPER_RUNS.read_text()
    assert text.startswith("# Generated by scripts/export_paper_runs.py")
    import yaml

    assert yaml.safe_load(text)["project"] == launch.PAPER_PROJECT


def test_schema(runs: dict[str, dict[str, Any]]) -> None:
    assert runs
    for run_id, e in runs.items():
        for key, typ in REQUIRED.items():
            assert isinstance(e.get(key), typ), f"{run_id}.{key}"
        recipe = get_recipe(e["task"], e["workflow"])
        assert e["share_policy"] in recipe.allowed_share_policy
        assert launch.normalize_scale(e["scale"]) == e["scale"]
        assert e["lr_warmup_steps"] in (0, 15), run_id
        assert e["control"] is None or e["control"] in launch.CONTROLS, run_id
        if e["task"] == "deepcoder":
            assert isinstance(e["code_executor_workers"], int)
        assert recipe_for_experiment(e["experiment_name"], e["task"]) is not None, run_id
        for ov in e["overrides"]:
            launch.parse_override(ov)


def test_grid_is_covered(runs: dict[str, dict[str, Any]]) -> None:
    canonical = {
        (e["task"], e["workflow"], e["share_policy"], e["scale"])
        for e in runs.values()
        if not e["cell"].startswith("control:")
    }
    expected = set()
    for task in ("math", "deepcoder"):
        for scale in ("0.6B", "1.7B", "4B"):
            expected.add((task, "single_agent", False, scale))
            for wf in ("voting", "evaluator_optimizer", "orchestrator_workers_propose"):
                expected |= {(task, wf, False, scale), (task, wf, True, scale)}
    assert canonical == expected
    assert len(expected) == 42


