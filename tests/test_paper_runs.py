def _check_against_config(run_id: str, entry: dict[str, Any], capsys: pytest.CaptureFixture[str]) -> None:
    rc = launch.cli(["--paper-run", run_id, "--paper-runs-file", str(PAPER_RUNS), "--print"])
    assert rc == 0
    argv = shlex.split(capsys.readouterr().out.strip())
    assert argv[:3] == ["python", "-m", launch.ENTRY_MODULE]
    cfg = json.loads((CACHE / run_id / "config.json").read_text())
    compared = 0
    for ov in argv[3:]:
        _, key, value = launch.parse_override(ov)
        if key in NOT_COMPARED:
            continue
        if key == "trainer.experiment_name" and entry.get("logged_experiment_name"):
            assert _get(cfg, key) == entry["logged_experiment_name"]
            continue
        assert _equal(_parse_value(value), _get(cfg, key)), f"{run_id}: {key}={value} vs logged {_get(cfg, key)!r}"
        compared += 1
    assert compared >= 10


