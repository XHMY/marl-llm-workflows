@needs_cache
def test_warmup_matches_logged_lr_series(runs: dict[str, dict[str, Any]]) -> None:
    pd = pytest.importorskip("pandas")
    for run_id, e in runs.items():
        hist = CACHE / (e["resumed_from"]["run"] if e.get("resumed_from") else run_id) / "history.parquet"
        df = pd.read_parquet(hist)
        step = "training/global_step" if "training/global_step" in df.columns else "_step"
        cols = [c for c in df.columns if c == "actor/lr" or (c.startswith("actor/") and c.endswith("/lr"))]
        sub = df[[step, *cols]].dropna(subset=cols, how="all").sort_values(step)
        if int(sub[step].iloc[0]) > 1:
            continue  # history starts after a resume; the predecessor decides (checked through resumed_from)
        first_lr = float(sub[cols].iloc[0].dropna().min())
        assert (first_lr < 2e-5 * 0.999) == (e["lr_warmup_steps"] == 15), run_id


@pytest.mark.skipif(not PAPER_TABLE.is_file(), reason="research fork paper table not available")
def test_every_canonical_run_id_present(runs: dict[str, dict[str, Any]]) -> None:
    import csv

    with open(PAPER_TABLE, newline="") as f:
        for r in csv.DictReader(f):
            if r["policy"] not in ("multi_lora", "share_policy") or r["run_id"].startswith("MISSING"):
                continue
            if r["workflow"] not in ("voting", "evaluator_optimizer", "orchestrator_workers_propose", "single_agent"):
                continue
            if r["cell"] != f"{r['workflow']}-{r['scale']}-{r['policy']}-{r['task']}":
                continue
            assert r["run_id"] in runs, r["cell"]
            assert runs[r["run_id"]]["experiment_name"] == r["cell"]
